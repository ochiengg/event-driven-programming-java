    private void btnNumberActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnNumberActionPerformed
       javax.swing.JButton clickedButton = (javax.swing.JButton) evt.getSource();
    String digit = clickedButton.getText();

    if (startNewNumber) {
        display.setText(digit);
        startNewNumber = false;
    } else {
        display.setText(display.getText() + digit);
    }
    }//GEN-LAST:event_btnNumberActionPerformed

    private void btnOperatorActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnOperatorActionPerformed
        javax.swing.JButton clickedButton = (javax.swing.JButton) evt.getSource();
    firstOperand = Double.parseDouble(display.getText());
    operator = clickedButton.getText();
    startNewNumber = true;
    }//GEN-LAST:event_btnOperatorActionPerformed

    private void btnEqualsActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEqualsActionPerformed
        double secondOperand = Double.parseDouble(display.getText());
    double result = 0;

    switch (operator) {
        case "+": result = firstOperand + secondOperand; break;
        case "-": result = firstOperand - secondOperand; break;
        case "*": result = firstOperand * secondOperand; break;
        case "/":
            if (secondOperand != 0) {
                result = firstOperand / secondOperand;
            } else {
                display.setText("Error");
                startNewNumber = true;
                return;
            }
            break;
        default: return;
    }

    display.setText(String.valueOf(result));
    startNewNumber = true;
    }//GEN-LAST:event_btnEqualsActionPerformed

    private void btnClearActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnClearActionPerformed
        display.setText("0");
    firstOperand = 0;
    operator = "";
    startNewNumber = true;
    }//GEN-LAST:event_btnClearActionPerformed

